"""build median time-versus-size plots from the raw benchmark csv"""

import argparse
import csv
import math
from collections import defaultdict
from pathlib import Path
from statistics import median

import matplotlib

# save figures on machines without a graphical desktop
matplotlib.use("Agg")
import matplotlib.pyplot as plt


ORDERS = {
    "random": ("Случайный", "#1768ac"),
    "ascending": ("Возрастающий", "#d47710"),
    "descending": ("Убывающий", "#41833b"),
}
OPERATIONS = {
    "build": "Построение дерева",
    "insert": "Вставка",
    "find_hit": "Успешный поиск",
    "find_miss": "Неуспешный поиск",
    "erase": "Удаление",
}


def read_measurements(path):
    """group raw repeats and reject incomplete series before drawing curves"""
    groups = defaultdict(list)
    seen = set()
    with path.open(newline="", encoding="utf-8") as source:
        for row in csv.DictReader(source):
            size = int(row["n"])
            operation = row["operation"]
            order = row["order"]
            repeat = int(row["repeat"])
            if size <= 0 or operation not in OPERATIONS or order not in ORDERS:
                raise ValueError("unknown operation, order or invalid size")
            identity = (size, order, operation, repeat)
            if identity in seen:
                raise ValueError(f"duplicate measurement: {identity}")
            seen.add(identity)
            # building is shown in seconds for the whole tree
            # the other plots show average nanoseconds per operation in each batch
            value = float(row["total_ms"]) / 1000 if operation == "build" else float(
                row["ns_per_operation"]
            )
            if not math.isfinite(value) or value < 0:
                raise ValueError("measurement must be finite and nonnegative")
            groups[(size, order, operation)].append(value)

    if not groups:
        raise ValueError("the CSV contains no measurements")

    sizes = sorted({size for size, _, _ in groups})
    counts = set()
    for size in sizes:
        for order in ORDERS:
            for operation in OPERATIONS:
                values = groups.get((size, order, operation))
                if not values:
                    raise ValueError(f"missing measurements: {size}, {order}, {operation}")
                counts.add(len(values))
    if len(counts) != 1:
        raise ValueError("all size/order/operation groups must have the same repeat count")
    return groups, sizes, counts.pop()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path, help="raw CSV generated by bench")
    parser.add_argument("--output", type=Path, default=Path("benchmarks/results/avl.png"))
    args = parser.parse_args()
    groups, sizes, repeats = read_measurements(args.csv)

    figure, axes = plt.subplots(2, 3, figsize=(15, 8.5), constrained_layout=True)
    for axis, (operation, title) in zip(axes.flat, OPERATIONS.items()):
        for order, (label, color) in ORDERS.items():
            values = [median(groups[(size, order, operation)]) for size in sizes]
            axis.plot(sizes, values, marker="o", linewidth=1.8, color=color, label=label)
        # logarithmic x spacing keeps both 10^4 and 10^7 readable in the same figure
        axis.set_xscale("log")
        if operation == "build":
            # construction spans milliseconds to seconds, so use log y to show small sizes
            axis.set_yscale("log")
        else:
            axis.set_ylim(bottom=0)
        axis.set_title(title)
        axis.set_xlabel("Количество элементов n")
        axis.set_ylabel("Время построения, с" if operation == "build" else "Среднее время, нс/операцию")
        axis.grid(True, which="both", alpha=0.25)

    axes.flat[-1].axis("off")
    handles, labels = axes.flat[0].get_legend_handles_labels()
    axes.flat[-1].legend(handles, labels, loc="upper left", frameon=False, fontsize=12)
    axes.flat[-1].text(
        0, 0.55,
        f"Медиана из {repeats} повторов\n"
        "Release, std::chrono::steady_clock\n"
        "Генерация данных вне измерений\n"
        "Поиск до вставки дополнительных ключей\n"
        "Удаление после вставки",
        transform=axes.flat[-1].transAxes, va="top", fontsize=10, linespacing=1.7,
    )
    figure.suptitle("AVLTree<int> — зависимость времени от размера дерева", fontsize=16)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(args.output, dpi=180)
    plt.close(figure)
    print(f"saved {args.output}")

    # export the same medians used in the figure so the report remains auditable
    summary = args.output.with_name(args.output.stem + "_medians.csv")
    with summary.open("w", newline="", encoding="utf-8") as destination:
        writer = csv.writer(destination)
        writer.writerow(["n", "order", "operation", "repeats", "median_time", "unit"])
        for size in sizes:
            for order in ORDERS:
                for operation in OPERATIONS:
                    writer.writerow([
                        size, order, operation, repeats,
                        median(groups[(size, order, operation)]),
                        "s" if operation == "build" else "ns/op",
                    ])
    print(f"saved {summary}")


if __name__ == "__main__":
    main()
